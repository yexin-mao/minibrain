def seed_demo(user: UserContext) -> dict[str, int]:
    """为一个用户登记示例知识；同名同内容文档和同名表格不会重复创建。"""
    document_ids = [
        gateway.call("vector-rag", "upload_document", user, None, filename, content)
        for filename, content in DEMO_DOCUMENTS.items()
    ]

    existing_tables = {
        str(row["filename"])
        for row in gateway.call("table-rag", "list_datasets", user)
    }
    table_ids = []
    for filename, raw in DEMO_TABLES.items():
        if filename in existing_tables:
            continue
        table_ids.append(
            gateway.call("table-rag", "upload_bytes", user, None, filename, raw)
        )

    return {
        "documents": len(document_ids),
        "new_tables": len(table_ids),
    }
