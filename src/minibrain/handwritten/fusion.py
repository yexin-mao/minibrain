"""RRF（Reciprocal Rank Fusion，倒数排名融合）。纯函数，可单测。

把多个排名合成一个。每条结果按它在各个排名里的**名次**算分：

    score(doc) = Σ  1 / (k + rank_in_that_list)

## 为什么用 RRF 而不是加权求和分数

因为**不同检索路径的分数不可比**。

余弦相似度在 0~1 之间，而且实测发现它的绝对值在不同查询之间也没有可比性
（见 eval/RESULTS.md：盲区查询里最低分 0.6011，对照查询里第二名才 0.4671）。
BM25 得分则是无上界的，取决于 IDF 和文档长度。

要把这两种分数加权相加，就得先各自归一化，而归一化方式的选择本身
就是一个需要调参的自由度——用 min-max 还是 z-score？按什么范围归？
**RRF 绕开了整件事：它只用名次，不用分数。**

代价是丢掉了"第一名比第二名强多少"这个信息。对本项目是划算的：
实测盲区查询里 8 篇的分数几乎一样（跨度 0.0738），那点差异本来就是噪声。

## 常数 k 的作用

k 越大，靠前名次之间的差距被压得越平。文献常用 k=60，本项目沿用，
没有调参——调参需要独立验证集，拿测试集调出来的数字是自欺。

    k=60 时：第 1 名得 1/61 = 0.0164，第 2 名 1/62 = 0.0161（差 2%）
    k=0  时：第 1 名得 1/1  = 1.0，  第 2 名 1/2  = 0.5  （差 50%）

k 大 → 更看重"在多个排名里都出现"；k 小 → 更看重"在某个排名里排第一"。
"""

from __future__ import annotations

from collections import defaultdict

RRF_K = 60


def reciprocal_rank_fusion(
    rankings: list[list[int]], *, k: int = RRF_K,
    tie_breaker: list[int] | None = None,
) -> list[tuple[int, float]]:
    """把若干个排名（下标列表，按相关性降序）融合成一个。

    返回 [(下标, 融合分), ...]，按融合分降序。

    只在某一个排名里出现的文档也会被收进来，只是分数低。
    这是 RRF 的重要性质：**一路召回不到的东西，另一路仍有机会带进来。**

    ## tie_breaker：为什么需要它

    实测发现一种**结构性平局**，项目编号那 8 题里有 4 题栽在这上面：

        向量：  错的那篇 第1，正确答案 第2
        关键词：正确答案 第1，错的那篇 第2
        RRF：   两边都是 1/61 + 1/62 → 完全相等

    两篇文档在两个排名里占据的名次集合都是 {1, 2}，**分数必然相同**。
    而且这跟 k 无关——k=10 照样平。任何对称的 RRF 都破不了这个局。

    默认按下标升序破平，那纯粹是为了可复现，**没有任何检索学上的意义**。
    传入 tie_breaker 就改成"按这个排名的名次"破平。

    调用方把**精度更高的那一路**传进来。本项目传的是关键词路。

    注意这**不是加权**：它只影响原本就完全相等、只能靠任意规则决定的情况。
    不引入需要调参的权重，也就不存在"在测试集上调参"的问题。

    ## 已知代价（实测，不是推测）

    "关键词路首位命中几乎必对"这句话**只对编号成立，对缩写不成立**：

      编号 PRJ-2026-0163  语料里只出现 1 次（DF=1）→ BM25 命中即确定
      缩写 QPS / P0 / P1   正当地出现在多篇里       → BM25 按词频排，
                                                   选的是"提得最多的"而非"下定义的"

    实测：问「QPS 的口径是怎么规定的？」
      向量：  metric-qps.md 第 1      ← 语义上"口径规定"就该匹配定义文档
      关键词：runbook-capacity.md 第 1（那篇提了两次 QPS），metric-qps.md 第 2

    所以启用 tie_breaker 后，英文缩写这一类 MRR 从 1.000 掉到 0.950
    （10 题里 1 题的正确答案从第 1 名变第 2 名，**仍在 top-5 内，不影响 Recall**）。

    换来的是：项目编号 +0.250、会议编号 +0.361、工单编号 +0.181，
    全局 MRR 0.855 → 0.950。**这个取舍是划算的，所以接受。**

    没有采纳的更精细方案：只在"命中词的文档频率极低"时才让关键词破平。
    它能同时保住缩写那 0.050，但要引入一个文档频率阈值——
    而那个阈值只能在评测集上选，本项目没有独立验证集。
    为了 1 道题的第 1 名 vs 第 2 名引入一个调参自由度，不值。
    """
    scores: dict[int, float] = defaultdict(float)
    for ranking in rankings:
        for position, index in enumerate(ranking, start=1):
            scores[index] += 1.0 / (k + position)

    tie_rank = {index: pos for pos, index in enumerate(tie_breaker or [])}
    LAST = len(tie_rank) + 1          # 不在 tie_breaker 里的排到最后

    return sorted(
        scores.items(),
        key=lambda item: (-item[1], tie_rank.get(item[0], LAST), item[0]),
    )
